import json
import logging
from typing import Any, Dict, Optional
import httpx
from app.core.config import settings

logger = logging.getLogger(__name__)

ADVISORY_DISCLAIMER = (
    "[ADVISORY NOTICE]: This automated LLM evaluation is non-binding heuristic advisory commentary. "
    "All decisions must be grounded in empirical bootstrap confidence intervals and paired statistical tests."
)

def redact_sensitive(text: str) -> str:
    return text.replace(settings.llm_api_key, "[REDACTED]") if settings.llm_api_key else text

def build_grounded_prompt(
    dataset_name: str,
    task_type: str,
    models_summary: Dict[str, Any],
    paired_tests: list,
    worst_slice: Optional[Dict[str, Any]],
    user_context: Optional[str] = None,
) -> str:
    prompt = (
        f"Auditor task: Analyze benchmark '{dataset_name}' ({task_type}).\n"
        f"Metrics & 95% CIs: {json.dumps(models_summary, indent=1)}\n"
        f"Paired Tests: {json.dumps(paired_tests, indent=1)}\n"
    )
    if worst_slice:
        prompt += f"Worst Slice: {worst_slice.get('cohort_name')}={worst_slice.get('cohort_value')}, Disparity: {worst_slice.get('disparity_ratio')}\n"
    if user_context:
        prompt += f"Auditor Context: {user_context}\n"
    prompt += "Analyze leader significance, slice risks, and alignment recommendations grounded in data."
    return prompt

def generate_deterministic_advisory(
    dataset_name: str,
    task_type: str,
    models_summary: Dict[str, Any],
    paired_tests: list,
    worst_slice: Optional[Dict[str, Any]],
) -> str:
    lines = [
        f"### Deterministic Arena Evaluation Summary: {dataset_name} ({task_type})",
        f"- Evaluated Models: {len(models_summary)} competing run(s).",
    ]
    sig_tests = [t for t in paired_tests if t.get("statistically_significant")]
    if sig_tests:
        lines.append(f"- Significance: {len(sig_tests)} comparison(s) significant at p < 0.05.")
        for t in sig_tests:
            lines.append(f"  * {t.get('model_a_name')} vs {t.get('model_b_name')}: Δ={t.get('difference')}, p={t.get('p_value')}")
    else:
        lines.append("- Significance: No pairwise differences significant at p < 0.05 within 95% bootstrap bounds.")
    if worst_slice:
        lines.append(f"- Slice Vulnerability: Worst cohort `{worst_slice.get('cohort_name')}={worst_slice.get('cohort_value')}` (disparity ratio {worst_slice.get('disparity_ratio')}).")
    lines.append("\n*(Offline evaluation generated by deterministic empirical engine.)*")
    return "\n".join(lines)

async def call_llm_advisor(
    dataset_name: str,
    task_type: str,
    models_summary: Dict[str, Any],
    paired_tests: list,
    worst_slice: Optional[Dict[str, Any]],
    user_context: Optional[str] = None,
) -> Dict[str, Any]:
    evidence = {"models_count": len(models_summary), "paired_tests_count": len(paired_tests), "worst_slice": worst_slice}
    if not settings.llm_api_key or not settings.llm_api_key.strip():
        text = generate_deterministic_advisory(dataset_name, task_type, models_summary, paired_tests, worst_slice)
        return {"status": "offline_deterministic", "provider": "deterministic-engine", "model": "rule-based", "analysis": text, "advisory_disclaimer": ADVISORY_DISCLAIMER, "grounded_evidence": evidence}

    prompt = build_grounded_prompt(dataset_name, task_type, models_summary, paired_tests, worst_slice, user_context)
    provider, base_url = settings.llm_provider.lower(), settings.llm_base_url.rstrip("/")

    try:
        async with httpx.AsyncClient(timeout=httpx.Timeout(settings.llm_timeout_seconds)) as client:
            if provider in ["openai-compatible", "ollama", "litellm", "openrouter"]:
                r = await client.post(f"{base_url}/chat/completions", headers={"Authorization": f"Bearer {settings.llm_api_key}"}, json={"model": settings.llm_model, "messages": [{"role": "user", "content": prompt}]})
                r.raise_for_status()
                content = r.json()["choices"][0]["message"]["content"]
            elif provider == "anthropic":
                r = await client.post(f"{base_url}/messages", headers={"x-api-key": settings.llm_api_key, "anthropic-version": "2023-06-01"}, json={"model": settings.llm_model, "max_tokens": 1500, "messages": [{"role": "user", "content": prompt}]})
                r.raise_for_status()
                content = r.json()["content"][0]["text"]
            elif provider == "gemini":
                r = await client.post(f"{base_url}/models/{settings.llm_model}:generateContent", headers={"x-goog-api-key": settings.llm_api_key}, json={"contents": [{"parts": [{"text": prompt}]}]})
                r.raise_for_status()
                content = r.json()["candidates"][0]["content"]["parts"][0]["text"]
            else:
                return {"status": "error", "provider": provider, "model": settings.llm_model, "analysis": f"Unsupported provider: {provider}", "advisory_disclaimer": ADVISORY_DISCLAIMER, "grounded_evidence": {}}
        return {"status": "success", "provider": provider, "model": settings.llm_model, "analysis": content, "advisory_disclaimer": ADVISORY_DISCLAIMER, "grounded_evidence": evidence}
    except Exception as exc:
        err = redact_sensitive(str(exc))
        logger.error("LLM Provider call failed: %s", err)
        return {"status": "provider_error", "provider": provider, "model": settings.llm_model, "analysis": f"Provider error: {err}", "advisory_disclaimer": ADVISORY_DISCLAIMER, "grounded_evidence": {}}
